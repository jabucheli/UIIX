function colorNivelRiesgo(valor) {
  if (valor <= 20) {
    return [0, 128, 0];        
  } else if (valor >= 20 && valor <= 120) {
    return [255, 255, 0];      
  } else if (valor >= 120 && valor <= 500) {
    return [255, 165, 0];      
  } else if (valor >= 500 && valor <= 4000) {
    return [255, 0, 0];        
  }
  return [255, 255, 255];     
}


