const codigosSinSufijo = new Set([
  "330", // Ruido
  "380", // Iluminación
  "340", // Vibración
  "570", // Organización del trabajo incorrecta
  "130", // Sobreesfuerzos
  "360", // Radiaciones ionizantes
  "390", // Asfixia o intoxicación
  "170"  // Sustancias nocivas
]);

function obtenerCodigoConSufijo(codigoBase, actividad) {
  if (!codigoBase) return codigoBase;

  // Si el código NO requiere sufijo
  if (codigosSinSufijo.has(codigoBase)) {
    return codigoBase;
  }

  const sufijo = actividad === "Edificación" ? "E" : "I";
  return `${codigoBase}-${sufijo}`;
}


