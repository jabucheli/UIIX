function mostrarTabla(proceso) {

  // Ordenar riesgos por código
  proceso.riesgos.sort((a, b) => parseInt(a[1], 10) - parseInt(b[1], 10));

  let html = `<h3>${proceso.nombre}</h3>`;

  html += `<table class="tabla-riesgos">
    <thead>
      <tr>
        <th>Peligro</th>
        <th>Código</th>
        <th>Riesgo</th>
        <th>Nivel de deficiencia (N)</th>
        <th>Nivel de exposición (NE)</th>
        <th>Nivel de probabilidad (NP)</th>
        <th>Nivel de consecuencia (NC)</th>
        <th>Nivel de riesgo (NR)</th>
        <th>Nivel de intervención (NI)</th>
      </tr>
    </thead>
    <tbody>`;

  proceso.riesgos.forEach(r => {
    html += `<tr>
      <td>${r[0]}</td>
      <td>${obtenerCodigoConSufijo(r[1], actividadesSelect.value)}</td>
      <td>${r[2]}</td>
      ${generarCeldaValorArgumento(r[3], true, "deficiencia")}
      ${generarCeldaValorArgumento(r[4], true, "exposicion")}
      ${generarCeldaValorArgumento(r[5], true, "probabilidad")}
      ${generarCeldaValorArgumento(r[6], true, "consecuencia")}
      <td>${r[7]}</td>
      ${generarCeldaValorArgumento(r[8], true, "intervencion")}
    </tr>`;
  });

  html += `</tbody></table>`;

  tablaDiv.innerHTML = html;
}


